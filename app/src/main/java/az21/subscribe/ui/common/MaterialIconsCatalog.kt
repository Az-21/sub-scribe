/**
 * A hand-picked set of common Material Icons offered alongside the full Simple Icons catalog.
 * Keys are namespaced material: so they never collide with a same-named Simple Icons slug.
 */
object MaterialIconsCatalog {
  val all: List<IconEntry> by lazy {
    CURATED_MATERIAL_ICONS
      .map { icon ->
        IconEntry(
          key = IconCatalog.MATERIAL_PREFIX + icon.slug,
          displayName = icon.displayName,
          vector = icon.vector,
          source = IconSource.MATERIAL,
          defaultColor = icon.defaultColor,
        )
      }.sortedBy { entry -> entry.displayName.lowercase(Locale.ROOT) }
  }
}

